-- 여러 번 실행해도 된다(있는 표는 건너뛰고 함수 · 권한 · 트리거는 새로 쓴다).
-- 절차 전체는 저장소 루트의 TASKMANAGER_SETUP.md.
--
-- 권한의 뼈대
--   · 계정(auth.users)이 생기면 tm_members 에 승인 대기로 한 줄이 생긴다. 저절로 승인되는 계정은 없다.
--     (누구나 로그인 화면에서 가입 요청을 보낼 수 있으므로 이것이 문이다)
--   · 승인 · 거절 · 승인 취소 · 관리자 지정은 관리자가 화면의 '팀원' 창에서 한다.
--     첫 관리자는 이 파일 맨 아래의 문장으로 SQL Editor 에서 정한다. 마지막 관리자는 내릴 수 없다.
--   · 작업 · 문서는 승인된 팀원만 읽고 쓴다(RLS). 로그인하지 않은 요청(anon)은 아무것도 못 본다.
--   · 개인 메모는 쓴 사람만 읽고 쓴다. 관리자도 남의 메모는 못 본다.
-- ═══════════════════════════════════════════════════════════════════════

-- ── 팀원 ─────────────────────────────────────────────────────
create table if not exists public.tm_members (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null default '',
  name text not null default '',
  role text not null default '',
  initial text not null default '',   -- 비우면 화면이 이름에서 만든다(박무경 → 무경)
  active boolean not null default false,
  is_admin boolean not null default false,   -- 승인 · 승인 취소 · 관리자 지정을 할 수 있다
  created_at timestamptz not null default now()
);
-- 관리자 칸이 생기기 전에 만든 표
alter table public.tm_members add column if not exists is_admin boolean not null default false;

-- ── 작업 ─────────────────────────────────────────────────────
create table if not exists public.tm_tasks (
  id uuid primary key default gen_random_uuid(),
  num bigint generated by default as identity (start with 100) unique,   -- 화면의 MATE-<num>
  title text not null default '',
  description text not null default '',
  status text not null default 'todo' check (status in ('backlog', 'todo', 'doing', 'review', 'done')),
  priority text not null default 'normal' check (priority in ('urgent', 'high', 'normal', 'low')),
  domain text not null default 'ops' check (domain in ('web', 'game', 'edu', 'ops')),
  assignee uuid references public.tm_members (id) on delete set null,
  start_date date,
  due_date date,
  labels text[] not null default '{}',
  sort double precision not null default 0,   -- 같은 상태 칸 안의 순서. 작을수록 위
  created_by uuid default auth.uid() references public.tm_members (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ── 문서 ─────────────────────────────────────────────────────
create table if not exists public.tm_docs (
  id uuid primary key default gen_random_uuid(),
  parent_id uuid references public.tm_docs (id) on delete cascade,   -- 위 문서를 지우면 아래 문서도 함께
  title text not null default '',
  body text not null default '',
  author uuid default auth.uid() references public.tm_members (id) on delete set null,
  labels text[] not null default '{}',
  sort double precision not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ── 개인 메모 ────────────────────────────────────────────────
-- 쓴 사람만 읽고 쓴다(아래 RLS). 계정이 지워지면 그 사람의 메모도 함께 지워진다
create table if not exists public.tm_memos (
  id uuid primary key default gen_random_uuid(),
  owner uuid not null default auth.uid() references public.tm_members (id) on delete cascade,
  title text not null default '',
  body text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 다른 표를 가리키는 칸 - 지울 때(on delete) · 묶어 볼 때 표 전체를 훑지 않게
create index if not exists tm_tasks_assignee_idx on public.tm_tasks (assignee);
create index if not exists tm_tasks_created_by_idx on public.tm_tasks (created_by);
create index if not exists tm_docs_parent_id_idx on public.tm_docs (parent_id);
create index if not exists tm_docs_author_idx on public.tm_docs (author);
create index if not exists tm_memos_owner_idx on public.tm_memos (owner);

-- ── 함수 ─────────────────────────────────────────────────────

-- 지금 요청한 사람이 승인된 팀원인가. RLS 에서 쓴다(security definer 라 tm_members 의 RLS 를 다시 타지 않는다)
create or replace function public.tm_is_member()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.tm_members m where m.id = auth.uid() and m.active)
$$;

-- 지금 요청한 사람이 승인된 관리자인가
create or replace function public.tm_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.tm_members m where m.id = auth.uid() and m.active and m.is_admin)
$$;

-- 고친 시각
create or replace function public.tm_touch()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- 계정이 생기면 팀원 줄을 만든다. 늘 승인 대기 · 관리자 아님으로(첫 계정도 저절로 승인하지 않는다)
create or replace function public.tm_on_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.tm_members (id, email, name, active, is_admin, created_at)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), split_part(coalesce(new.email, ''), '@', 1)),
    false,
    false,
    coalesce(new.created_at, now())
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

-- 팀원 줄을 고칠 때의 규칙 - 이름 · 역할은 자기 것만, 승인 · 관리자 여부는 관리자가 다른 사람 것만,
-- 승인된 관리자가 하나도 남지 않게는 못 한다. 승인을 취소하면 관리자에서도 빠진다
create or replace function public.tm_members_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  -- 승인을 취소하면 관리자 표시도 지운다 - 나중에 다시 승인했을 때 관리자 권한이 말없이 되살아나지 않게
  if old.active and not new.active then
    new.is_admin := false;
  end if;
  -- 마지막 관리자는 SQL Editor 에서도 내리지 못한다. 둘이 동시에 서로를 내리지 못하게 관리자 줄을 잠그고 센다
  if old.active and old.is_admin and not (new.active and new.is_admin) then
    perform 1 from public.tm_members m where m.active and m.is_admin for update;
    if not exists (select 1 from public.tm_members m where m.id <> new.id and m.active and m.is_admin) then
      raise exception '마지막 관리자는 승인을 취소하거나 관리자에서 뺄 수 없습니다. 다른 사람을 먼저 관리자로 정해 주세요';
    end if;
  end if;
  -- 대시보드 · SQL Editor 처럼 로그인한 사용자를 거치지 않는 쪽은 그 밖의 것은 무엇이든 고칠 수 있다
  if auth.uid() is null then
    return new;
  end if;
  if new.id <> old.id or new.email <> old.email or new.created_at <> old.created_at then
    raise exception '바꿀 수 없는 칸입니다';
  end if;
  if (new.active, new.is_admin) is distinct from (old.active, old.is_admin) then
    if not public.tm_is_admin() then
      raise exception '승인과 관리자 지정은 관리자만 바꿀 수 있습니다';
    end if;
    if new.id = auth.uid() then
      raise exception '자기 승인과 관리자 여부는 바꿀 수 없습니다';
    end if;
  end if;
  if (new.name, new.role, new.initial) is distinct from (old.name, old.role, old.initial)
     and new.id <> auth.uid() then
    raise exception '다른 사람의 이름과 역할은 바꿀 수 없습니다';
  end if;
  return new;
end;
$$;

-- 가입 요청 거절 - 승인 대기 계정을 계정째 지운다(팀원 줄은 cascade 로 함께). 같은 메일로 다시 요청할 수 있다.
-- 관리자만, 자기 계정은 못 지운다. 지우는 동안 다른 관리자가 승인하지 못하게 그 줄을 잠근다
create or replace function public.tm_reject_member(target uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.tm_is_admin() then
    raise exception '가입 요청은 관리자만 거절할 수 있습니다';
  end if;
  if target = auth.uid() then
    raise exception '자기 계정은 지울 수 없습니다';
  end if;
  perform 1 from public.tm_members m where m.id = target and not m.active for update;
  if not found then
    raise exception '승인 대기 중인 계정만 거절할 수 있습니다';
  end if;
  delete from auth.users u where u.id = target;
end;
$$;

-- ── 트리거 ───────────────────────────────────────────────────
drop trigger if exists tm_tasks_touch on public.tm_tasks;
create trigger tm_tasks_touch before update on public.tm_tasks
  for each row execute function public.tm_touch();

drop trigger if exists tm_docs_touch on public.tm_docs;
create trigger tm_docs_touch before update on public.tm_docs
  for each row execute function public.tm_touch();

drop trigger if exists tm_memos_touch on public.tm_memos;
create trigger tm_memos_touch before update on public.tm_memos
  for each row execute function public.tm_touch();

drop trigger if exists tm_members_guard on public.tm_members;
create trigger tm_members_guard before update on public.tm_members
  for each row execute function public.tm_members_guard();

drop trigger if exists tm_on_new_user on auth.users;
create trigger tm_on_new_user after insert on auth.users
  for each row execute function public.tm_on_new_user();

-- ── 이 SQL 보다 먼저 만든 계정 ───────────────────────────────
insert into public.tm_members (id, email, name, created_at)
select u.id, coalesce(u.email, ''), split_part(coalesce(u.email, ''), '@', 1), u.created_at
from auth.users u
on conflict (id) do nothing;

-- 저절로 승인하지 않는다. 첫 관리자는 이 파일 맨 아래의 문장으로 정한다

-- ── 읽고 쓰는 권한(RLS) ──────────────────────────────────────
alter table public.tm_members enable row level security;
alter table public.tm_tasks enable row level security;
alter table public.tm_docs enable row level security;
alter table public.tm_memos enable row level security;

-- 팀원 목록: 승인된 팀원은 모두를, 승인 대기 중인 사람은 자기 줄만 본다
drop policy if exists tm_members_select on public.tm_members;
create policy tm_members_select on public.tm_members
  for select to authenticated
  using ((select public.tm_is_member()) or id = (select auth.uid()));

drop policy if exists tm_members_update on public.tm_members;
create policy tm_members_update on public.tm_members
  for update to authenticated
  using ((select public.tm_is_member()) or id = (select auth.uid()))
  with check ((select public.tm_is_member()) or id = (select auth.uid()));

drop policy if exists tm_tasks_members on public.tm_tasks;
create policy tm_tasks_members on public.tm_tasks
  for all to authenticated
  using ((select public.tm_is_member()))
  with check ((select public.tm_is_member()));

drop policy if exists tm_docs_members on public.tm_docs;
create policy tm_docs_members on public.tm_docs
  for all to authenticated
  using ((select public.tm_is_member()))
  with check ((select public.tm_is_member()));

-- 개인 메모: 쓴 사람만. 주인을 남으로 바꿔 넘기지도 못한다. 승인이 취소되면 자기 메모도 못 연다(다시 승인되면 그대로 있다)
drop policy if exists tm_memos_owner on public.tm_memos;
create policy tm_memos_owner on public.tm_memos
  for all to authenticated
  using (owner = (select auth.uid()) and (select public.tm_is_member()))
  with check (owner = (select auth.uid()) and (select public.tm_is_member()));

-- Supabase 가 새 표에 기본으로 주는 권한(TRUNCATE 등)을 모두 거두고, 화면이 쓰는 것만 다시 준다
revoke all on public.tm_members, public.tm_tasks, public.tm_docs, public.tm_memos from anon, authenticated;
grant select, update on public.tm_members to authenticated;
grant select, insert, update, delete on public.tm_tasks, public.tm_docs, public.tm_memos to authenticated;

-- 함수도 기본으로 누구나 실행할 수 있어 /rest/v1/rpc 로 불린다. 트리거용은 아무도 부르지 못하게 하고
-- RLS 가 쓰는 두 개(승인된 팀원인가 · 관리자인가)와 가입 요청 거절만 로그인한 사람에게 남긴다(거절은 함수가 관리자인지 본다).
-- 트리거는 이 권한과 상관없이 돈다
revoke execute on function public.tm_is_member(), public.tm_is_admin(), public.tm_touch(),
  public.tm_on_new_user(), public.tm_members_guard(), public.tm_reject_member(uuid) from public, anon, authenticated;
grant execute on function public.tm_is_member(), public.tm_is_admin(), public.tm_reject_member(uuid) to authenticated;

-- ── 실시간 - 다른 사람이 고친 것이 새로고침 없이 보이게 ──────
-- 메모는 RLS 를 거쳐 쓴 사람에게만 간다(지운 알림만은 RLS 를 거치지 않아 id 만 실려 모두에게 간다 - 내용은 없다)
do $$
begin
  begin
    alter publication supabase_realtime add table public.tm_members;
  exception when duplicate_object then null;
  end;
  begin
    alter publication supabase_realtime add table public.tm_tasks;
  exception when duplicate_object then null;
  end;
  begin
    alter publication supabase_realtime add table public.tm_docs;
  exception when duplicate_object then null;
  end;
  begin
    alter publication supabase_realtime add table public.tm_memos;
  exception when duplicate_object then null;
  end;
end;
$$;

