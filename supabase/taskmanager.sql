-- MATE 작업 관리 도구(/taskmanager) - Supabase 표 · 권한 · 실시간
--
-- 쓰는 법: Supabase 대시보드 → SQL Editor → New query 에 이 파일을 통째로 붙여 넣고 Run.
-- 여러 번 실행해도 된다(있는 표는 건너뛰고 함수 · 권한 · 트리거는 새로 쓴다).
-- 절차 전체는 저장소 루트의 TASKMANAGER_SETUP.md.
--
-- 권한의 뼈대
--   · 계정(auth.users)이 생기면 tm_members 에 승인 대기로 한 줄이 생긴다. 저절로 승인되는 계정은 없다.
--     (누구나 로그인 화면에서 가입 요청을 보낼 수 있으므로 이것이 문이다)
--   · 승인 · 거절 · 승인 취소 · 관리자 지정은 관리자가 화면의 '팀원' 창에서 한다.
--     첫 관리자는 이 파일 맨 아래의 문장으로 SQL Editor 에서 정한다. 마지막 관리자는 내릴 수 없다.
--   · 작업 · 문서는 승인된 팀원만 읽고 쓴다(RLS). 로그인하지 않은 요청(anon)은 아무것도 못 본다.
--   · 개인 메모는 쓴 사람만 읽고 쓴다. 관리자도 남의 메모는 못 본다.
--   · 영역(작업을 가르는 갈래)은 팀원 모두 읽고, 고치기는 영역을 맡은 사람만 한다.
--     맡은 사람은 관리자와 따로, 이 파일 맨 아래의 문장으로 SQL Editor 에서만 정한다.
-- ═══════════════════════════════════════════════════════════════════════

-- ── 팀원 ─────────────────────────────────────────────────────
create table if not exists public.tm_members (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null default '',
  name text not null default '',
  role text not null default '',
  initial text not null default '',   -- 비우면 화면이 이름에서 만든다(박무경 → 무경)
  active boolean not null default false,
  is_admin boolean not null default false,   -- 승인 · 승인 취소 · 관리자 지정을 할 수 있다
  domain_editor boolean not null default false,   -- 영역을 고칠 수 있다(관리자와 따로, SQL Editor 에서만 정한다)
  created_at timestamptz not null default now()
);
-- 관리자 · 영역 칸이 생기기 전에 만든 표
alter table public.tm_members add column if not exists is_admin boolean not null default false;
alter table public.tm_members add column if not exists domain_editor boolean not null default false;

-- ── 영역 ─────────────────────────────────────────────────────
-- 작업을 가르는 갈래(웹 · 앱, 게임 · XR …). 색은 화면의 네 가지 - 빨강 · 호박색 · 초록은 급함 · 임박 · 끝남의 뜻이라 영역에 주지 않는다
create table if not exists public.tm_domains (
  id text primary key,
  label text not null check (char_length(btrim(label)) between 1 and 20),
  short text not null default '' check (char_length(short) <= 10),   -- 보드 카드의 알약. 비우면 화면이 이름을 쓴다
  color text not null default 'gray' check (color in ('blue', 'violet', 'teal', 'gray')),
  sort double precision not null default 0,   -- 메뉴 순서. 작을수록 위
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
-- 처음 네 영역 - 작업 표가 처음부터 가리키던 값이라 id 는 그대로 둔다.
-- 표가 비어 있을 때만 넣는다(다시 실행해도 맡은 사람이 지운 영역을 되살리지 않게)
insert into public.tm_domains (id, label, short, color, sort)
select v.id, v.label, v.short, v.color, v.sort
from (values
  ('web', '웹 · 앱', 'WEB', 'blue', 1000::double precision),
  ('game', '게임 · XR', 'GAME', 'violet', 2000),
  ('edu', '교육 · 강의', 'EDU', 'teal', 3000),
  ('ops', '내부 · 운영', 'OPS', 'gray', 4000)
) as v (id, label, short, color, sort)
where not exists (select 1 from public.tm_domains);

-- ── 작업 ─────────────────────────────────────────────────────
create table if not exists public.tm_tasks (
  id uuid primary key default gen_random_uuid(),
  num bigint generated by default as identity (start with 100) unique,   -- 화면의 MATE-<num>
  title text not null default '',
  description text not null default '',
  status text not null default 'todo' check (status in ('backlog', 'todo', 'doing', 'review', 'done')),
  priority text not null default 'normal' check (priority in ('urgent', 'high', 'normal', 'low')),
  domain text not null default 'ops',   -- 영역(tm_domains). 외래 키는 아래에서 건다
  assignee uuid references public.tm_members (id) on delete set null,
  start_date date,
  due_date date,
  labels text[] not null default '{}',
  sort double precision not null default 0,   -- 같은 상태 칸 안의 순서. 작을수록 위
  created_by uuid default auth.uid() references public.tm_members (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
-- 영역이 정해진 네 값이던 때의 규칙(tm_tasks_domain_check)을 영역 표를 가리키는 외래 키로 바꾼다.
-- 작업이 남은 영역은 지워지지 않는다 - 지우기는 tm_domain_remove 가 작업을 옮긴 뒤에 한다
alter table public.tm_tasks drop constraint if exists tm_tasks_domain_check;
alter table public.tm_tasks drop constraint if exists tm_tasks_domain_fkey;
alter table public.tm_tasks add constraint tm_tasks_domain_fkey
  foreign key (domain) references public.tm_domains (id) on update cascade;

-- ── 문서 ─────────────────────────────────────────────────────
create table if not exists public.tm_docs (
  id uuid primary key default gen_random_uuid(),
  parent_id uuid references public.tm_docs (id) on delete cascade,   -- 위 문서를 지우면 아래 문서도 함께
  title text not null default '',
  body text not null default '',
  author uuid default auth.uid() references public.tm_members (id) on delete set null,
  labels text[] not null default '{}',
  sort double precision not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ── 개인 메모 ────────────────────────────────────────────────
-- 쓴 사람만 읽고 쓴다(아래 RLS). 계정이 지워지면 그 사람의 메모도 함께 지워진다
create table if not exists public.tm_memos (
  id uuid primary key default gen_random_uuid(),
  owner uuid not null default auth.uid() references public.tm_members (id) on delete cascade,
  title text not null default '',
  body text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 위키 칸 - 아이콘, 마지막으로 내용을 고친 사람, 휴지통(비어 있으면 살아 있는 문서).
-- 사람을 가리키지만 외래 키는 두지 않는다 - 팀원 계정을 지울 때 문서가 막지 않게(화면은 모르는 사람으로 적는다)
alter table public.tm_docs add column if not exists icon text not null default '';
alter table public.tm_docs add column if not exists updated_by uuid;
alter table public.tm_docs add column if not exists trashed_at timestamptz;
alter table public.tm_docs add column if not exists trashed_by uuid;

-- ── 문서 기록 ── 고치기 전 모습. 남기는 것은 트리거와 tm_doc_snapshot 이 하고 화면은 읽기만 한다
create table if not exists public.tm_doc_versions (
  id uuid primary key default gen_random_uuid(),
  doc_id uuid not null references public.tm_docs (id) on delete cascade,
  title text not null default '',
  body text not null default '',
  edited_by uuid,                                   -- 이 모습으로 마지막에 고친 사람
  edited_at timestamptz not null default now(),     -- 이 모습이 저장된 시각
  created_at timestamptz not null default now()
);

-- ── 문서 댓글 ── 답글은 한 단계(parent_id 는 맨 위 댓글). 지우기는 removed 표시로 자리만 남긴다
create table if not exists public.tm_doc_comments (
  id uuid primary key default gen_random_uuid(),
  doc_id uuid not null references public.tm_docs (id) on delete cascade,
  parent_id uuid references public.tm_doc_comments (id) on delete cascade,
  author uuid default auth.uid(),
  body text not null default '',
  resolved boolean not null default false,
  removed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()      -- 본문을 고친 시각(해결 표시로는 바뀌지 않는다)
);

-- 다른 표를 가리키는 칸 - 지울 때(on delete) · 묶어 볼 때 표 전체를 훑지 않게
create index if not exists tm_tasks_assignee_idx on public.tm_tasks (assignee);
create index if not exists tm_tasks_created_by_idx on public.tm_tasks (created_by);
create index if not exists tm_tasks_domain_idx on public.tm_tasks (domain);
create index if not exists tm_docs_parent_id_idx on public.tm_docs (parent_id);
create index if not exists tm_docs_author_idx on public.tm_docs (author);
create index if not exists tm_doc_versions_doc_idx on public.tm_doc_versions (doc_id, created_at desc);
create index if not exists tm_doc_comments_doc_idx on public.tm_doc_comments (doc_id);
create index if not exists tm_doc_comments_parent_idx on public.tm_doc_comments (parent_id);
create index if not exists tm_memos_owner_idx on public.tm_memos (owner);

-- ── 함수 ─────────────────────────────────────────────────────

-- 지금 요청한 사람이 승인된 팀원인가. RLS 에서 쓴다(security definer 라 tm_members 의 RLS 를 다시 타지 않는다)
create or replace function public.tm_is_member()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.tm_members m where m.id = auth.uid() and m.active)
$$;

-- 지금 요청한 사람이 승인된 관리자인가
create or replace function public.tm_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.tm_members m where m.id = auth.uid() and m.active and m.is_admin)
$$;

-- 지금 요청한 사람이 영역을 고칠 수 있는가 - 승인된 팀원 가운데 영역을 맡은 사람(관리자와 따로 정한다)
create or replace function public.tm_can_edit_domains()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.tm_members m where m.id = auth.uid() and m.active and m.domain_editor)
$$;

-- 고친 시각
create or replace function public.tm_touch()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- 계정이 생기면 팀원 줄을 만든다. 늘 승인 대기 · 관리자 아님으로(첫 계정도 저절로 승인하지 않는다)
create or replace function public.tm_on_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.tm_members (id, email, name, active, is_admin, created_at)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), split_part(coalesce(new.email, ''), '@', 1)),
    false,
    false,
    coalesce(new.created_at, now())
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

-- 팀원 줄을 고칠 때의 규칙 - 이름 · 역할은 자기 것만, 승인 · 관리자 여부는 관리자가 다른 사람 것만,
-- 승인된 관리자가 하나도 남지 않게는 못 한다. 승인을 취소하면 관리자 · 영역 맡기에서도 빠진다.
-- 영역을 맡은 사람은 SQL Editor 에서만 정한다(로그인한 사용자는 관리자라도 못 바꾼다)
create or replace function public.tm_members_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is not null and new.domain_editor is distinct from old.domain_editor then
    raise exception '영역을 맡을 사람은 SQL Editor 에서만 정할 수 있습니다';
  end if;
  -- 승인을 취소하면 관리자 · 영역 맡기 표시도 지운다 - 나중에 다시 승인했을 때 권한이 말없이 되살아나지 않게
  if old.active and not new.active then
    new.is_admin := false;
    new.domain_editor := false;
  end if;
  -- 마지막 관리자는 SQL Editor 에서도 내리지 못한다. 둘이 동시에 서로를 내리지 못하게 관리자 줄을 잠그고 센다
  if old.active and old.is_admin and not (new.active and new.is_admin) then
    perform 1 from public.tm_members m where m.active and m.is_admin for update;
    if not exists (select 1 from public.tm_members m where m.id <> new.id and m.active and m.is_admin) then
      raise exception '마지막 관리자는 승인을 취소하거나 관리자에서 뺄 수 없습니다. 다른 사람을 먼저 관리자로 정해 주세요';
    end if;
  end if;
  -- 대시보드 · SQL Editor 처럼 로그인한 사용자를 거치지 않는 쪽은 그 밖의 것은 무엇이든 고칠 수 있다
  if auth.uid() is null then
    return new;
  end if;
  if new.id <> old.id or new.email <> old.email or new.created_at <> old.created_at then
    raise exception '바꿀 수 없는 칸입니다';
  end if;
  if (new.active, new.is_admin) is distinct from (old.active, old.is_admin) then
    if not public.tm_is_admin() then
      raise exception '승인과 관리자 지정은 관리자만 바꿀 수 있습니다';
    end if;
    if new.id = auth.uid() then
      raise exception '자기 승인과 관리자 여부는 바꿀 수 없습니다';
    end if;
  end if;
  if (new.name, new.role, new.initial) is distinct from (old.name, old.role, old.initial)
     and new.id <> auth.uid() then
    raise exception '다른 사람의 이름과 역할은 바꿀 수 없습니다';
  end if;
  return new;
end;
$$;

-- 가입 요청 거절 - 승인 대기 계정을 계정째 지운다(팀원 줄은 cascade 로 함께). 같은 메일로 다시 요청할 수 있다.
-- 관리자만, 자기 계정은 못 지운다. 지우는 동안 다른 관리자가 승인하지 못하게 그 줄을 잠근다
create or replace function public.tm_reject_member(target uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.tm_is_admin() then
    raise exception '가입 요청은 관리자만 거절할 수 있습니다';
  end if;
  if target = auth.uid() then
    raise exception '자기 계정은 지울 수 없습니다';
  end if;
  perform 1 from public.tm_members m where m.id = target and not m.active for update;
  if not found then
    raise exception '승인 대기 중인 계정만 거절할 수 있습니다';
  end if;
  delete from auth.users u where u.id = target;
end;
$$;

-- 영역 지우기 - 그 영역의 작업을 move_to 로 옮기고 지운다. 영역을 맡은 사람만.
-- 옮길 영역이 따로 있어야 하므로 마지막 영역은 지울 수 없다. 둘이 동시에 서로 다른 영역을 지워 하나도 남지 않게 되지 않도록 영역 줄을 잠근다
create or replace function public.tm_domain_remove(target text, move_to text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.tm_can_edit_domains() then
    raise exception '영역은 맡은 사람만 지울 수 있습니다';
  end if;
  if target = move_to then
    raise exception '작업을 옮길 영역은 지울 영역과 달라야 합니다';
  end if;
  perform 1 from public.tm_domains d for update;
  if not exists (select 1 from public.tm_domains d where d.id = move_to) then
    raise exception '작업을 옮길 영역이 없습니다. 화면을 새로고침해 주세요';
  end if;
  update public.tm_tasks t set domain = move_to where t.domain = target;
  delete from public.tm_domains d where d.id = target;
end;
$$;

-- 문서를 고칠 때 - 제목 · 본문이 바뀌면 고친 사람을 적고, 새로 고치기 시작했으면 그 전 모습을 기록에 남긴다.
-- 새로 시작 = 마지막으로 고친 사람이 다르거나 10분 넘게 손대지 않았다. 한 사람이 오래 이어서 고치면 30분마다 한 번 남긴다.
-- 두 사람이 번갈아 저장해도 사람이 바뀔 때의 기록은 1분에 한 번만 - 저장마다 남기면 기록이 금세 넘친다
create or replace function public.tm_docs_history()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.title is not distinct from old.title and new.body is not distinct from old.body then
    return new;
  end if;
  new.updated_by := coalesce(auth.uid(), new.updated_by);
  if (old.updated_by is distinct from new.updated_by and not exists (
       select 1 from public.tm_doc_versions v
       where v.doc_id = old.id and v.created_at > now() - interval '1 minute'
     ))
     or old.updated_at < now() - interval '10 minutes'
     or not exists (
       select 1 from public.tm_doc_versions v
       where v.doc_id = old.id and v.created_at > now() - interval '30 minutes'
     ) then
    insert into public.tm_doc_versions (doc_id, title, body, edited_by, edited_at)
    values (old.id, old.title, old.body, old.updated_by, old.updated_at);
  end if;
  return new;
end;
$$;

-- 문서의 '누가' 칸은 DB 가 정한다 - 쓴 사람은 만든 사람으로 고정, 휴지통에 넣은 사람은 넣은 사람,
-- 마지막으로 고친 사람은 내용을 바꾼 사람(tm_docs_history). 화면이 다른 이름을 보내도 따르지 않는다
create or replace function public.tm_docs_stamp()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  -- 대시보드 · SQL Editor 처럼 로그인한 사용자를 거치지 않는 쪽은 그대로 둔다
  if auth.uid() is null then
    return new;
  end if;
  if tg_op = 'INSERT' then
    new.author := auth.uid();
    new.updated_by := auth.uid();
    new.trashed_at := null;
    new.trashed_by := null;
    return new;
  end if;
  new.author := old.author;
  if new.trashed_at is distinct from old.trashed_at then
    new.trashed_by := case when new.trashed_at is null then null else auth.uid() end;
  else
    new.trashed_by := old.trashed_by;
  end if;
  if new.title is not distinct from old.title and new.body is not distinct from old.body then
    new.updated_by := old.updated_by;
  end if;
  return new;
end;
$$;

-- 문서를 자기 아래(자기 하위 문서 밑)로 옮기지 못하게 한다 - 고리가 생기면 트리에서 사라진다
create or replace function public.tm_docs_guard()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.parent_id is not null and (tg_op = 'INSERT' or new.parent_id is distinct from old.parent_id) then
    if new.parent_id = new.id or exists (
      with recursive up (id, parent_id) as (
        select d.id, d.parent_id from public.tm_docs d where d.id = new.parent_id
        union
        select d.id, d.parent_id from public.tm_docs d join up on d.id = up.parent_id
      )
      select 1 from up where up.id = new.id
    ) then
      raise exception '문서를 자기 아래로 옮길 수 없습니다';
    end if;
  end if;
  return new;
end;
$$;

-- 지금 모습을 기록에 남긴다 - 예전 판으로 되돌리기 직전에 화면이 부른다(되돌린 것도 되돌릴 수 있게)
create or replace function public.tm_doc_snapshot(target uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.tm_is_member() then
    raise exception '승인된 팀원만 기록을 남길 수 있습니다';
  end if;
  insert into public.tm_doc_versions (doc_id, title, body, edited_by, edited_at)
  select d.id, d.title, d.body, d.updated_by, d.updated_at
  from public.tm_docs d
  where d.id = target
    and not exists (
      select 1 from public.tm_doc_versions v
      where v.doc_id = d.id and v.edited_at = d.updated_at and v.title = d.title and v.body = d.body
    );
end;
$$;

-- 댓글 규칙 - 쓴 사람 · 쓴 시각은 DB 가 적고, 본문 고치기 · 지우기는 쓴 사람만. 해결 표시는 누구나.
-- 답글은 같은 문서의 맨 위 댓글에만 단다
create or replace function public.tm_doc_comments_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if auth.uid() is not null then
      new.author := auth.uid();
      new.created_at := now();
    end if;
    new.removed := false;
    new.updated_at := new.created_at;
    if new.parent_id is not null and not exists (
      select 1 from public.tm_doc_comments p
      where p.id = new.parent_id and p.doc_id = new.doc_id and p.parent_id is null
    ) then
      raise exception '답글은 같은 문서의 댓글에만 달 수 있습니다';
    end if;
    return new;
  end if;
  if (new.id, new.doc_id, new.parent_id, new.author, new.created_at)
     is distinct from (old.id, old.doc_id, old.parent_id, old.author, old.created_at) then
    raise exception '바꿀 수 없는 칸입니다';
  end if;
  if old.removed and not new.removed then
    raise exception '지운 댓글은 되살릴 수 없습니다';
  end if;
  if auth.uid() is not null and old.author is distinct from auth.uid()
     and (new.body, new.removed) is distinct from (old.body, old.removed) then
    raise exception '다른 사람의 댓글은 고치거나 지울 수 없습니다';
  end if;
  if new.removed then
    new.body := '';
  end if;
  if new.body is distinct from old.body and not new.removed then
    new.updated_at := now();
  else
    new.updated_at := old.updated_at;
  end if;
  return new;
end;
$$;

